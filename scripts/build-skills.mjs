// Generates the skills served over the MCP Skills extension from kernel/skills
// at a pinned commit. Production build uses the committed module; regenerate
// after bumping SKILLS_COMMIT with: bun run build:skills
// --check fetches the pinned commit and fails if the committed module differs.
import { createHash } from "node:crypto";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { extname, join, resolve } from "node:path";

const SKILLS_REPOSITORY = "https://github.com/kernel/skills.git";
const SKILLS_COMMIT = "4376bb1057e60d1377fb42dbe41de35689b4aa5a";
// Skill directories in the repository. Each is served at skill://<dir name>/.
const SKILL_DIRECTORIES = ["skills/kernel-mcp"];

// Per-skill limits every conforming host must accept (SEP-2640).
const MAX_FILES_PER_SKILL = 512;
const MAX_BYTES_PER_SKILL = 16 * 1024 * 1024;

const MIME_TYPES = {
  ".md": "text/markdown",
  ".txt": "text/plain",
  ".json": "application/json",
  ".yaml": "application/yaml",
  ".yml": "application/yaml",
  ".py": "text/x-python",
  ".sh": "text/x-shellscript",
  ".js": "text/javascript",
  ".mjs": "text/javascript",
  ".ts": "text/typescript",
  ".html": "text/html",
  ".svg": "image/svg+xml",
  ".png": "image/png",
};

const root = resolve(import.meta.dirname, "..");
const generatedPath = join(root, "src/lib/mcp/skills/generated/skills.ts");
const check = process.argv.includes("--check");
const temp = await mkdtemp(join(tmpdir(), "kernel-skills-"));

async function git(args, { binary = false } = {}) {
  const proc = Bun.spawn(["git", "-C", temp, ...args], {
    stdout: "pipe",
    stderr: "pipe",
  });
  const [stdout, stderr, code] = await Promise.all([
    new Response(proc.stdout).arrayBuffer(),
    new Response(proc.stderr).text(),
    proc.exited,
  ]);
  if (code !== 0) throw new Error(`git ${args.join(" ")} failed: ${stderr}`);
  return binary ? new Uint8Array(stdout) : new TextDecoder().decode(stdout);
}

function parseFrontmatter(text, path) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/.exec(text);
  if (!match) throw new Error(`${path} has no YAML frontmatter`);
  const frontmatter = Bun.YAML.parse(match[1]);
  if (
    typeof frontmatter?.name !== "string" ||
    typeof frontmatter?.description !== "string"
  ) {
    throw new Error(`${path} frontmatter needs a name and description`);
  }
  return frontmatter;
}

try {
  await git(["init", "--quiet"]);
  await git([
    "fetch",
    "--quiet",
    "--depth=1",
    SKILLS_REPOSITORY,
    SKILLS_COMMIT,
  ]);

  const skills = [];
  for (const directory of SKILL_DIRECTORIES) {
    const skillName = directory.split("/").at(-1);
    const tree = await git([
      "ls-tree",
      "-r",
      "-z",
      SKILLS_COMMIT,
      "--",
      `${directory}/`,
    ]);
    const files = [];
    for (const entry of tree.split("\0").filter(Boolean)) {
      const [info, path] = entry.split("\t");
      const [mode, type, object] = info.split(" ");
      if (type !== "blob" || mode === "120000") {
        throw new Error(`${path} is not a regular file`);
      }
      const bytes = await git(["cat-file", "blob", object], { binary: true });
      const relativePath = path.slice(directory.length + 1);
      const mimeType =
        MIME_TYPES[extname(relativePath).toLowerCase()] ??
        "application/octet-stream";
      let text;
      try {
        text = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
      } catch {
        // Binary content is served as a base64 blob.
      }
      files.push({
        path: relativePath,
        mimeType,
        size: bytes.byteLength,
        digest: `sha256:${createHash("sha256").update(bytes).digest("hex")}`,
        ...(text === undefined
          ? { blob: Buffer.from(bytes).toString("base64") }
          : { text }),
      });
    }

    const skillFile = files.find((file) => file.path === "SKILL.md");
    if (!skillFile?.text) throw new Error(`${directory} has no SKILL.md`);
    const frontmatter = parseFrontmatter(
      skillFile.text,
      `${directory}/SKILL.md`,
    );
    if (frontmatter.name !== skillName) {
      throw new Error(
        `${directory}/SKILL.md name "${frontmatter.name}" must match its directory`,
      );
    }
    const totalBytes = files.reduce((sum, file) => sum + file.size, 0);
    if (
      files.length > MAX_FILES_PER_SKILL ||
      totalBytes > MAX_BYTES_PER_SKILL
    ) {
      throw new Error(`${directory} exceeds the per-skill limits`);
    }
    skills.push({ name: skillName, frontmatter, files });
  }

  const generated = `// Generated by scripts/build-skills.mjs from kernel/skills@${SKILLS_COMMIT}. Do not edit.
import type { BundledSkill } from "@/lib/mcp/skills/types";

export const BUNDLED_SKILLS: BundledSkill[] = ${JSON.stringify(skills, null, 2)};
`;

  if (check) {
    let current = "";
    try {
      current = await readFile(generatedPath, "utf8");
    } catch {
      // Report the same actionable stale-module error below.
    }
    if (current !== generated) {
      console.error("Bundled skills are stale. Run: bun run build:skills");
      process.exitCode = 1;
    }
  } else {
    await mkdir(resolve(generatedPath, ".."), { recursive: true });
    await writeFile(generatedPath, generated);
    console.log(`Generated ${generatedPath}`);
  }
} finally {
  await rm(temp, { recursive: true, force: true });
}
